def main():
    s = open(PATH, encoding='utf-8').read()
    # drop any previous generated block
    s = re.sub(re.escape(START) + r'.*?' + re.escape(END) + r'\n?', '', s, flags=re.S)
    blocks = list(re.finditer(r'<style[^>]*>(.*?)</style>', s, re.S))
    big = max(blocks, key=lambda m: len(m.group(1)))
    css = strip_comments(big.group(1))
    gen_css = gen(css)
    for dark, light in (('#4a3410', '#f7e7bf'), ('#3a2c0e', '#f1e2bb')):
        gen_css = gen_css.replace(dark, light)   # dark-brown gradient end stops the converter does not map
    gen_css = gen_css.replace('body:not(.tab-insight-active)', 'body:not(.light-off)')
    block = START + '\n' + gen_css + MANUAL.replace('body:not(.tab-insight-active)', 'body:not(.light-off)') + END + '\n'
    pos = big.end(1)
    s = s[:pos] + '\n' + block + s[pos:]

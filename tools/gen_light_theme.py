# Gold text on cream is ~1.7:1; this brass is ~4.7:1. Elements sitting on a dark surface keep real gold (BRASS_SKIP).
BRASS = '#8f6208'
BRASS_SKIP = ['.chart-view-lock', '.chart-share-btn']   # pills with a dark-grey fill: keep gold

# ---------------------------------------------------------------- colours
NAMED = {'white': (255, 255, 255, 1.0), 'black': (0, 0, 0, 1.0)}

def parse_color(tok):
    t = tok.strip().lower()
    if t in NAMED:
        return NAMED[t]
    if t.startswith('#'):
        h = t[1:]
        if len(h) in (3, 4):
            h = ''.join(c * 2 for c in h)
        if len(h) == 6:
            h += 'ff'
        if len(h) != 8:
            return None
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), int(h[6:8], 16) / 255.0)
    m = re.match(r'rgba?\(([^()]*)\)$', t)
    if m:
        parts = [p for p in re.split(r'[\s,/]+', m.group(1).strip()) if p]
        if len(parts) < 3 or any('var' in p for p in parts):
            return None
        try:
            vals = []
            for p in parts[:3]:
                vals.append(float(p[:-1]) * 2.55 if p.endswith('%') else float(p))
            a = 1.0
            if len(parts) > 3:
                a = float(parts[3][:-1]) / 100 if parts[3].endswith('%') else float(parts[3])
            return (vals[0], vals[1], vals[2], a)
        except ValueError:
            return None
    return None

def lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]

def sat(c):
    return max(c[:3]) - min(c[:3])

def is_gold(c):
    return c[0] > 150 and c[0] >= c[1] and c[1] > c[2] + 40 and sat(c) > 70

def warm_dark(c):
    return c[0] > c[2] + 30 and c[1] > c[2] + 15 and sat(c) > 35

def fmt(r, g, b, a=1.0):
    r, g, b = [max(0, min(255, int(round(x)))) for x in (r, g, b)]
    if a >= 0.999:
        return '#%02x%02x%02x' % (r, g, b)
    return 'rgba(%d,%d,%d,%s)' % (r, g, b, ('%.3f' % a).rstrip('0').rstrip('.'))

def mix_white(c, t):
    return tuple(c[i] + (255 - c[i]) * t for i in range(3))

# exact palette values used all over the app -> their light twins
EXACT = {
    (0x14, 0x16, 0x1a): '#f3f0e8',   # --bg  (page)
    (0x1c, 0x1f, 0x24): '#ffffff',   # --panel
    (0x24, 0x28, 0x30): '#f1ede4',   # --panel-2
    (0x2a, 0x2f, 0x38): '#e9e4d9',   # --panel-3
    (0x2e, 0x33, 0x3b): '#dcd6c8',   # --line
}

def bg_map(c):
    """Replacement for a background colour, or None to keep it."""
    r, g, b, a = c
    if a < 0.04 or is_gold(c) or warm_dark(c):
        return None
    l = lum(c)
    if a < 0.5:                      # translucent shading / glass
        if l < 90:
            return fmt(40, 34, 20, a * 0.30)
        return None
    if l < 16 and a < 0.97:          # near-black scrim behind modals: stays dark
        return None
    key = (int(round(r)), int(round(g)), int(round(b)))
    if key in EXACT:
        return fmt(*[int(EXACT[key][i:i + 2], 16) for i in (1, 3, 5)], a)
    if sat(c) > 28 and l < 130:      # dark green/red/blue fills -> pastel
        return fmt(*mix_white(c, 0.86), a)
    if l < 28:  return fmt(243, 240, 232, a)
    if l < 36:  return fmt(255, 255, 255, a)
    if l < 44:  return fmt(241, 237, 228, a)
    if l < 60:  return fmt(233, 228, 217, a)
    if l < 100: return fmt(226, 220, 207, a)
    if l < 130: return fmt(218, 211, 196, a)
    return None

def text_map(c):
    r, g, b, a = c
    if a < 0.04 or is_gold(c):
        return None
    l = lum(c)
    if sat(c) > 60:
        if l > 150:                  # bright green/red/blue text -> deeper so it reads on white
            return fmt(r * 0.58, g * 0.58, b * 0.58, a)
        return None
    if l > 190: return fmt(28, 30, 35, a)
    if l > 140: return fmt(91, 97, 106, a)
    if l > 100: return fmt(118, 123, 131, a)
    return None

def border_map(c):
    r, g, b, a = c
    if a < 0.02 or is_gold(c):
        return None
    l = lum(c)
    if l > 200 and a < 0.9:
        return fmt(40, 34, 20, min(0.22, max(a * 0.8, 0.17)))   # floor: faint card outlines must stay visible on the page
    if l < 90 and a >= 0.5 and sat(c) < 40:
        return fmt(196, 188, 170, a)    # solid dark outlines -> a visible warm grey (was #dcd6c8, nearly invisible on cream)
    return None

COLOR_RE = re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b|rgba?\([^()]*\)|\b(?:white|black)\b')

def map_colors(value, fn):
    changed = [False]
    def sub(m):
        c = parse_color(m.group(0))
        if c is None:
            return m.group(0)
        n = fn(c)
        if n is None:
            return m.group(0)
        changed[0] = True
        return n
    out = COLOR_RE.sub(sub, value)
    return out, changed[0]

PHOTO_RE = re.compile(r"url\(\s*['\"]?[^)]*?(?:-bg|background|photo)[^)]*?\.(?:jpe?g|webp|png)['\"]?\s*\)", re.I)

# ---------------------------------------------------------------- css parsing
def strip_comments(css):
    return re.sub(r'/\*.*?\*/', '', css, flags=re.S)

def split_top(text, sep):
    out, depth, cur, q = [], 0, [], None
    for ch in text:
        if q:
            cur.append(ch)
            if ch == q:
                q = None
            continue
        if ch in '"\'':
            q = ch; cur.append(ch); continue
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(''.join(cur)); cur = []
        else:
            cur.append(ch)
    out.append(''.join(cur))
    return out

def parse_blocks(css):
    """Yield (prelude, body) for each top-level block in css."""
    i, n, res = 0, len(css), []
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k, q = 1, j + 1, None
        while k < n and depth:
            ch = css[k]
            if q:
                if ch == q: q = None
            elif ch in '"\'':
                q = ch
            elif ch == '{': depth += 1
            elif ch == '}': depth -= 1
            k += 1
        res.append((prelude, css[j + 1:k - 1]))
        i = k
    return res

NOT_INSIGHT = ':not(.tab-insight-active)'

def prefix_selector(sel):
    """Scope a selector to light mode, and exclude the Insight tab (its 3D scene is
    hard-coded dark, so that whole tab keeps the dark theme)."""
    sel = sel.strip()
    if sel.startswith(':root'):
        return 'html[data-theme="light"]' + sel[5:]
    m = re.match(r'html(?![\w-])((?:\[[^\]]*\]|\.[\w-]+|:[\w-]+(?:\([^)]*\))?)*)(.*)$', sel, re.S)
    if m:
        head, rest = 'html[data-theme="light"]' + m.group(1), m.group(2)
    else:
        head, rest = 'html[data-theme="light"]', ' ' + sel
    rest = rest if rest.startswith((' ', '>', '+', '~')) or not rest else ' ' + rest
    r = rest.lstrip()
    if r.startswith('body') and not re.match(r'body[\w-]', r):
        mm = re.match(r'body((?:\.[\w-]+|\[[^\]]*\])*)(.*)$', r, re.S)
        return head + ' body' + mm.group(1) + NOT_INSIGHT + mm.group(2)
    return head + ' body' + NOT_INSIGHT + (' ' + r if r else '')

def light_decls(body, sel=''):
    decls = []
    for d in split_top(body, ';'):
        d = d.strip()
        if not d or ':' not in d:
            continue
        p, v = d.split(':', 1)
        imp = ''
        v = v.strip()
        if re.search(r'!\s*important\s*$', v):
            imp = ' !important'
            v = re.sub(r'\s*!\s*important\s*$', '', v)
        decls.append((p.strip().lower(), v, imp))

    # does this rule paint its own non-dark solid colour? then leave its text colour alone
    keep_text = False
    for p, v, imp in decls:
        if p in ('background', 'background-color', 'background-image'):
            if re.search(r'var\(--(accent|success|accent-2)\b', v):
                keep_text = True
            for tok in COLOR_RE.findall(v):
                c = parse_color(tok)
                if c and c[3] >= 0.5 and bg_map(c) is None:
                    keep_text = True

    out = []
    for p, v, imp in decls:
        nv = None
        if p in ('background', 'background-color', 'background-image'):
            if 'var(--accent-dim)' in v:
                # dark olive fill (dark-mode token) + brass text = unreadable on cream -> soft gold tint
                out.append('%s:%s%s' % (p, v.replace('var(--accent-dim)', 'rgba(var(--accent-rgb),0.22)'), imp))
                continue
            if PHOTO_RE.search(v) or 'hero-background' in v:
                fill = '#f3f0e8' if re.search(r'overlay|page|pricing|screen|boot|splash|auth', sel) else '#ffffff'
                if p == 'background-image':
                    out.append('background-image:none' + imp)
                    out.append('background-color:%s%s' % (fill, imp))
                else:
                    out.append(('background' if p == 'background' else p) + ':' + fill + imp)
                continue
            nv, ch = map_colors(v, bg_map)
            if not ch: nv = None
        elif p in ('color', '-webkit-text-fill-color', 'fill', 'stroke', 'caret-color'):
            if p in ('color', '-webkit-text-fill-color') and keep_text:
                continue
            nv, ch = map_colors(v, text_map)
            if not ch: nv = None
        elif p == 'border' or p.startswith('border-') or p in ('outline', 'outline-color', 'column-rule'):
            if 'radius' in p or 'width' in p or 'style' in p or 'collapse' in p or 'spacing' in p or 'image' in p:
                continue
            if 'var(--accent-dim)' in v:
                # dark-mode olive outline token: far too heavy on cream -> soft gold outline
                out.append('%s:%s%s' % (p, v.replace('var(--accent-dim)', 'rgba(var(--accent-rgb),0.7)'), imp))
                continue
            nv, ch = map_colors(v, border_map)
            if not ch: nv = None
        elif p in ('box-shadow', 'filter', 'text-shadow', '-webkit-box-shadow'):
            if p == 'filter':
                continue
            if re.search(r'\b(9999px|100vmax|200vmax|100vh|200vh)\b', v):
                continue            # full-screen dimmer (tour spotlight) stays dark
            def shadow(c):
                if c[3] > 0.02 and lum(c) < 60:
                    return fmt(70, 55, 25, min(0.16, c[3] * 0.4))
                return None
            nv, ch = map_colors(v, shadow)
            if not ch: nv = None
        elif p == 'color-scheme' and v.strip() == 'dark':
            nv = 'light'
        if nv is not None and nv != v:
            out.append('%s:%s%s' % (p, nv, imp))
    return out

def gen(css, indent=''):
    out = []
    for prelude, body in parse_blocks(css):
        if prelude.startswith('@'):
            if re.match(r'@(media|supports)\b', prelude):
                inner = gen(body, indent + '  ')
                if inner.strip():
                    out.append('%s%s{\n%s%s}\n' % (indent, prelude, inner, indent))
            continue   # @keyframes, @font-face, @page ... untouched
        sels = [s.strip() for s in split_top(prelude, ',') if s.strip()]
        sels = [s for s in sels if not any(k in s for k in SKIP_SELECTORS)]
        if not sels:
            continue
        decls = light_decls(body, prelude)
        # small gold text -> brass. Scoped with :where() so it adds NO specificity: state rules such as
        # `.btn.go{color:#1c1500}` (dark text on a gold button) still win over it.
        for d in split_top(body, ';'):
            if ':' in d and d.split(':', 1)[0].strip().lower() == 'color' and d.split(':', 1)[1].strip().lower() in ('var(--accent)', '#f2b134'):
                bs = [s for s in sels if not any(k in s for k in BRASS_SKIP)]
                if bs:
                    out.append('%s%s{color:%s}\n' % (indent, ','.join(':where(html[data-theme="light"] body:not(.tab-insight-active)) ' + s for s in bs), BRASS))
                break
        if not decls:
            continue
        out.append('%s%s{%s}\n' % (indent, ','.join(prefix_selector(s) for s in sels), ';'.join(decls)))
    return ''.join(out)

